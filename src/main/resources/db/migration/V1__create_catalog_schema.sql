CREATE TABLE
  colors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hex_code VARCHAR(7) NOT NULL,
    name VARCHAR(255),
    CONSTRAINT uk_colors_hex_code UNIQUE (hex_code)
  );

CREATE TABLE
  sizes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) NOT NULL,
    label VARCHAR(255),
    position INTEGER NOT NULL
  );

CREATE TABLE
  products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    short_description VARCHAR(200) NOT NULL,
    main_img_url VARCHAR(255) NOT NULL,
    CONSTRAINT uk_products_title UNIQUE (title)
  );

CREATE TABLE
  product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(12) NOT NULL,
    product_id BIGINT NOT NULL,
    color_id BIGINT NOT NULL,
    size_id BIGINT NOT NULL,
    original_price DECIMAL(12, 2) NOT NULL,
    sale_price DECIMAL(12, 2),
    is_active BOOLEAN NOT NULL,
    CONSTRAINT fk_product_variants_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_product_variants_color FOREIGN KEY (color_id) REFERENCES colors (id),
    CONSTRAINT fk_product_variants_size FOREIGN KEY (size_id) REFERENCES sizes (id)
  );

CREATE TABLE
  product_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    img_url VARCHAR(255) NOT NULL,
    product_variant_id BIGINT,
    CONSTRAINT fk_product_images_variant FOREIGN KEY (product_variant_id) REFERENCES product_variants (id)
  );